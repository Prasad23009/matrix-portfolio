-- Run this once in Supabase SQL Editor.
-- Project files themselves stay in a Supabase Storage bucket named: project-documents
-- This table only stores the public link and the information shown on the website.

create table if not exists public.project_documents (
  id integer generated by default as identity primary key,
  project_id integer not null references public.projects(id) on delete cascade,
  title varchar(180) not null,
  document_type varchar(40) not null default 'PDF',
  public_url varchar(2000) not null,
  display_order integer not null default 0
);

create index if not exists project_documents_project_id_display_order_idx
  on public.project_documents (project_id, display_order);

